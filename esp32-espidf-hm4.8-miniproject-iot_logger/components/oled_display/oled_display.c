void oled_display_init(void) {
    i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address  = SSD1306_ADDR,
        .scl_speed_hz    = I2C_FREQ_HZ,
    };
    ESP_ERROR_CHECK(i2c_master_bus_add_device(i2c_bus_handle(), &dev_cfg, &s_oled_handle));

    u8g2_hal_set_i2c_device(s_oled_handle);
    u8g2_Setup_ssd1306_i2c_128x64_noname_f(&u8g2, U8G2_R0, u8g2_esp32_i2c_byte_cb, u8g2_esp32_gpio_and_delay_cb);
    u8g2_InitDisplay(&u8g2);
    u8g2_SetPowerSave(&u8g2, 0);
}

void oled_play_wolf_boot_animation(uint32_t anim_duration_ms) {
    int64_t duration_us = anim_duration_ms * 1000;
    int64_t start = esp_timer_get_time();

    while (esp_timer_get_time() - start < duration_us) {
        u8g2_ClearBuffer(&u8g2);
        u8g2_DrawXBM(&u8g2, 48, 16, 32, 32, wolf_logo_32x32_open);    // 48=(128-32)/2, 16=(64-32)/2
        u8g2_SendBuffer(&u8g2);
        vTaskDelay(pdMS_TO_TICKS(500));

        u8g2_ClearBuffer(&u8g2);
        u8g2_DrawXBM(&u8g2, 48, 16, 32, 32, wolf_logo_32x32_blink);
        u8g2_SendBuffer(&u8g2);
        vTaskDelay(pdMS_TO_TICKS(150));
    }
}

void oled_draw_text(const char *message) {
    u8g2_ClearBuffer(&u8g2);
    u8g2_SetFont(&u8g2, u8g2_font_ncenB08_tf);
    u8g2_DrawStr(&u8g2, 4, 64/2, message);
    u8g2_SendBuffer(&u8g2);
}

void oled_draw_dashboard(
    const rtc_time_t *time,
    const bme280_data_t *bme,
    float threshold_c,
    bool led_on,
    const char *led_source
) {
    char line_time[16];
    snprintf(line_time, sizeof(line_time), "%02u:%02u:%02u", time->hour, time->min, time->sec);
    
    char line_bme_temp[14];
    snprintf(line_bme_temp, sizeof(line_bme_temp), "BME: %.1fC", bme->temperature);

    char line_meteo[20];
    snprintf(line_meteo, sizeof(line_meteo), "RH=%.0f%%  P=%.0fhPa", bme->humidity, bme->pressure);

    char line_threshold[16];
    snprintf(line_threshold, sizeof(line_threshold), "Threshold: %.1fC", threshold_c);

    char line_led[24];
    snprintf(line_led, sizeof(line_led), "LED: %s (%s)", led_on ? "ON" : "OFF", led_source);

    u8g2_ClearBuffer(&u8g2);
    u8g2_SetFont(&u8g2, u8g2_font_logisoso20_tr);
    u8g2_DrawStr(&u8g2, 4, 22, line_time);
    u8g2_SetFont(&u8g2, u8g2_font_ncenB08_tf);
    u8g2_DrawStr(&u8g2, 4, 32, line_bme_temp);
    u8g2_DrawStr(&u8g2, 4, 42, line_meteo);
    u8g2_DrawStr(&u8g2, 4, 52, line_threshold);
    u8g2_DrawStr(&u8g2, 4, 62, line_led);
    u8g2_SendBuffer(&u8g2);
}
