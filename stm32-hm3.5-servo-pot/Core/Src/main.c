uint16_t adc_raw_filtered(void) {
    uint32_t adc_sum = 0;
    for (int i = 0; i < ADC_SAMPLES; i++) {
        adc_sum += adc_buffer[i];
    }
    return (uint16_t)(adc_sum / ADC_SAMPLES);
}

float adc_to_pot_angle(uint16_t adc_raw) {
    float angle = ((float)adc_raw / 4095.0f) * POT_MAX_ANGLE;

    // cut for working zone 1:1 (45°..225°)
    if (angle < POT_START_ANGLE) {
        return 0.0f;
    } else if (angle > POT_END_ANGLE) {
        return SERVO_MAX_ANGLE;
    } else {
        return angle - POT_START_ANGLE;
    }
}

uint32_t angle_to_ccr(float angle) {
    if (angle < 0) return SERVO_MIN_PULSE_US;
    if (angle > SERVO_MAX_ANGLE) return SERVO_MAX_PULSE_US;

    float pulse_us = SERVO_MIN_PULSE_US + (angle / SERVO_MAX_ANGLE) * (SERVO_MAX_PULSE_US - SERVO_MIN_PULSE_US);
    return (uint32_t)pulse_us;
}

