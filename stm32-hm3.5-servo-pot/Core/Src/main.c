    /* USER CODE BEGIN 3 */

      uint16_t adc_raw = adc_raw_filtered();
      float angle = adc_to_pot_angle(adc_raw);

      if (fabsf(angle - last_angle) > 2) {
          last_angle = angle;
          last_ccr = angle_to_ccr(angle);
          __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, last_ccr);
      }

      uint32_t now = HAL_GetTick();
      if (now - last_time > 500) {
          last_time = now;
          printf("Angle: %d, ccr: %lu, raw: %u\r\n", (int)last_angle, last_ccr, adc_raw);
      }

      HAL_Delay(20); // 20 ms (corresponds to a servo frequency of 50 Hz)
